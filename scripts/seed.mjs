// Loads the researched seed data (seed/) into the D1 database.
//
//   npm run db:seed:local    -> the copy of the database on your computer
//   npm run db:seed:remote   -> the real database on Cloudflare
//
// Every record goes in as `needs_review`, so the editors approve each one in the admin queue.
// Safe to run more than once: after a complete load it records the seed in `seed_log`, and
// every later run does nothing. If a run stops halfway, running it again fills in only what
// is missing. It never changes or removes a record that already exists, so editors' changes,
// approvals, editor_notes, flags and "UNVERIFIED" markers are never overwritten.
import fs from 'node:fs';
import path from 'node:path';
import { executeFile, targetFromArgs } from './lib/d1.mjs';
import { SEED_DIR, SEED_ID, deriveFilters, loadSeed, validateSeed, yearSort } from './lib/seed-data.mjs';

const target = targetFromArgs();
const dryRun = process.argv.includes('--dry-run');

const seed = loadSeed();
const problems = validateSeed(seed);
if (problems.length) {
	console.error('The seed data has problems, so nothing was loaded:\n- ' + problems.join('\n- '));
	process.exit(1);
}

// ---------------------------------------------------------------------------
// Build the SQL
// ---------------------------------------------------------------------------

/** SQL literal: strings quoted with '' escaping, numbers as-is, null/undefined as NULL. */
function lit(value) {
	if (value === null || value === undefined) return 'NULL';
	if (typeof value === 'boolean') return value ? '1' : '0';
	if (typeof value === 'number') return String(value);
	return `'${String(value).replace(/'/g, "''")}'`;
}

const guard = `WHERE NOT EXISTS (SELECT 1 FROM seed_log WHERE seed_id = ${lit(SEED_ID)})`;

/**
 * INSERT that skips rows that already exist, and skips everything once this seed is logged.
 * `unlessExists` adds a check for tables whose rows have no natural key (edit_history).
 */
function insert(table, row, unlessExists = '') {
	const cols = Object.keys(row);
	const extra = unlessExists ? ` AND NOT EXISTS (SELECT 1 FROM ${table} WHERE ${unlessExists})` : '';
	return `INSERT OR IGNORE INTO ${table} (${cols.join(', ')}) SELECT ${cols.map((c) => lit(row[c])).join(', ')} ${guard}${extra};`;
}

/** The "seeded" line in a record's version history, written at most once per record. */
function seededHistory(entity_type, entity_id) {
	return insert(
		'edit_history',
		{
			entity_type,
			entity_id,
			action: 'seeded',
			editor: 'seed',
			note: `Loaded from the researched seed data (${SEED_ID}).`
		},
		`entity_type = ${lit(entity_type)} AND entity_id = ${lit(entity_id)} AND action = 'seeded'`
	);
}

const sql = [`-- Generated by scripts/seed.mjs from seed/ (seed ${SEED_ID}). Do not edit by hand.`];
const today = new Date().toISOString().slice(0, 10);

// Taxonomy
seed.taxonomy.drawers.forEach((d, i) => {
	sql.push(insert('drawers', { id: d.id, number: d.number, label: d.label, blurb: d.blurb ?? '', position: i }));
	d.subdrawers.forEach((s, j) => {
		sql.push(
			insert('subdrawers', {
				drawer_id: d.id,
				id: s.id,
				label: s.label,
				blurb: seed.subdrawerBlurbs[s.id] ?? null,
				position: j
			})
		);
	});
});

// Entries
for (const e of seed.entries) {
	sql.push(
		insert('entries', {
			id: e.id,
			type: e.type,
			catalogue_number: e.catalogue_number,
			name: e.name,
			ai: e.ai ? 1 : 0,
			website: e.website ?? null,
			release_year: e.release_year ?? null,
			description: e.card.description,
			facts: JSON.stringify(e.card.facts),
			notes: JSON.stringify(e.card.notes),
			research: JSON.stringify(e.research ?? {}),
			researched: e.researched ?? null,
			...deriveFilters(e),
			status: 'needs_review',
			source: 'seed',
			last_updated: e.last_updated ?? today
		})
	);
	e.drawers.forEach((drawer_id, position) =>
		sql.push(insert('entry_drawers', { entry_id: e.id, drawer_id, position }))
	);
	e.subdrawers.forEach((subdrawer_id, position) =>
		sql.push(insert('entry_subdrawers', { entry_id: e.id, subdrawer_id, position }))
	);
	sql.push(seededHistory('entry', e.id));
}

// Projects
for (const p of seed.projects) {
	sql.push(
		insert('projects', {
			id: p.id,
			title: p.title,
			short_title: p.short_title ?? null,
			year: p.year ?? null,
			year_sort: yearSort(p.year),
			who: p.who ?? null,
			kind: p.kind,
			how_used: p.how_used ?? null,
			url: p.url ?? null,
			flags: JSON.stringify(p.flags ?? []),
			editor_notes: p.editor_notes ?? '',
			verified: p.verified ?? null,
			status: 'needs_review',
			source: 'seed',
			last_updated: p.verified ?? today
		})
	);
	sql.push(seededHistory('project', p.id));
}

// Project–entry links (from links.csv)
for (const l of seed.links) {
	sql.push(insert('project_entries', { project_id: l.project_id, entry_id: l.entry_id }));
}

// Guides
for (const g of seed.guides) {
	sql.push(insert('guides', { entry_id: g.entry_id, title: g.title, url: g.url, status: 'needs_review', source: 'seed' }));
}

// Record the load last, so an interrupted run can be repeated.
const counts = {
	entries: seed.entries.length,
	tools: seed.entries.filter((e) => e.type === 'tool').length,
	datasets: seed.entries.filter((e) => e.type === 'dataset').length,
	projects: seed.projects.length,
	links: seed.links.length,
	guides: seed.guides.length
};
sql.push(`INSERT OR IGNORE INTO seed_log (seed_id, counts) VALUES (${lit(SEED_ID)}, ${lit(JSON.stringify(counts))});`);

// ---------------------------------------------------------------------------
// Write and run
// ---------------------------------------------------------------------------

const outDir = path.join(SEED_DIR, '.generated');
fs.mkdirSync(outDir, { recursive: true });
const outFile = path.join(outDir, `seed-${SEED_ID}.sql`);
fs.writeFileSync(outFile, sql.join('\n') + '\n', 'utf8');

console.log(`Seed ${SEED_ID}: ${counts.entries} entries (${counts.tools} tools, ${counts.datasets} datasets), ` +
	`${counts.projects} projects, ${counts.links} links, ${counts.guides} guides.`);
console.log(`SQL written to ${path.relative(process.cwd(), outFile)} (${sql.length} statements).`);

if (dryRun) {
	console.log('Dry run: nothing loaded.');
} else {
	console.log(`Loading into the ${target === '--remote' ? 'Cloudflare (remote)' : 'local'} database…`);
	const ran = executeFile(outFile, target);
	console.log(`Done: ${ran} statements run. Records that already existed were left untouched.`);
	console.log('Next: Run `npm run db:verify' + (target === '--remote' ? ':remote' : ':local') + '` to check it.');
}
